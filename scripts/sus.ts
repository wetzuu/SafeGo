// Scores the recorded usability sessions and writes docs/USABILITY_RESULTS.md.
// Record each session in data/usability/sessions.csv first (see docs/USABILITY_SESSIONS.md).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseSessions, summarize, susScore, TASKS } from "../lib/usability/sus.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sessions = parseSessions(readFileSync(join(root, "data/usability/sessions.csv"), "utf8"));
const result = summarize(sessions);
const round = (value: number | null) => value === null ? "—" : value.toFixed(1);

const lines = [
  "# SafeGo usability results",
  "",
  "Generated by `npm run sus` from `data/usability/sessions.csv`. Do not edit by hand.",
  "",
];

if (!result.participants) {
  lines.push("No sessions have been recorded yet. Run them with docs/USABILITY_SESSIONS.md, then rerun `npm run sus`.", "");
} else {
  lines.push(
    "## SUS score",
    "",
    `- **Participants:** ${result.participants}`,
    `- **Mean:** ${round(result.mean)} (median ${round(result.median)}, range ${round(result.min)}–${round(result.max)})`,
    "- **Reading it:** 68 is the commonly cited average across published SUS studies. With this few participants, " +
      "treat the score as a rough signal, not a measurement.",
    "",
    "## Tasks",
    "",
    "| Task | Done unaided | Done with help | Not done |",
    "| --- | --- | --- | --- |",
    ...result.tasks.map((task) => `| ${task.name} | ${task.unaided} of ${result.participants} | ${task.withHelp} | ${task.failed} |`),
    "",
    "## Sessions",
    "",
    `| Participant | Date | Device | Mode | SUS | ${TASKS.map((_, index) => `T${index + 1}`).join(" | ")} | Notes |`,
    `| --- | --- | --- | --- | --- | ${TASKS.map(() => "---").join(" | ")} | --- |`,
    ...sessions.map((session) =>
      `| ${session.participant} | ${session.date} | ${session.device} | ${session.mode} | ${susScore(session.sus)} | ${session.tasks.join(" | ")} | ${session.notes.replace(/\|/g, "/")} |`),
    "",
  );
}

writeFileSync(join(root, "docs/USABILITY_RESULTS.md"), lines.join("\n"));
console.log(result.participants
  ? `${result.participants} sessions. Mean SUS ${round(result.mean)}. Wrote docs/USABILITY_RESULTS.md`
  : "No sessions recorded yet. Wrote docs/USABILITY_RESULTS.md");
